/**
 * Bundle atlas: which dependency actually occupies the shipped JavaScript (r20-R3-1).
 *
 * `scripts/check-dist.mjs` already refuses a *size regression* — it compares the entry
 * chunk against a byte ceiling. It cannot answer the next question, which is who is
 * inside those bytes. The answer is in the sourcemaps the build already emits
 * (`dist/assets/*.js.map`, 22 of them in this checkout), so no instrumentation,
 * no rebuild and no new dependency is needed: a `.map`'s `sources` list names every
 * module that went into the chunk, and its `mappings` say how much of each one survived.
 *
 * Method, and its honest limit: the per-source byte figure is **not** a minifier-exact
 * measurement. It is computed by taking the chunk's generated byte span (the sum of each
 * generated line's final column, i.e. roughly the `.js` file's own size) and splitting it
 * among sources by the share of mapping segments that point at each source. That is
 * enough to rank packages and to spot a dependency that arrived unnoticed; it is not
 * enough to bill a byte count against a budget. `check-dist.mjs` remains the gate; this
 * is the microscope.
 *
 * Two decoding rules this script used to get WRONG (r21-o1), because the resulting report
 * was wrong in a way that looked plausible — see the commit that fixed it:
 *   - a segment's source index is field 2 and is **relative to the previous segment's
 *     value**, accumulating across the whole `mappings` string; only the generated column
 *     (field 1) resets per line. The old code read field 4 (the original *column* delta)
 *     as an absolute index, so attribution followed column deltas instead of sources —
 *     it charged the react-dom chunk 26.3% to `scheduler`, which is really ~0.5% of it.
 *   - the per-chunk byte total was the longest `mappings` *line character count*, which
 *     counts encoding characters, not code bytes.
 *
 * Usage:
 *   node scripts/bundle-atlas.mjs --dist dist [--top 25] [--json .pack/bundle-atlas.json]
 * Exit codes follow this repo's checker contract (0 = produced a report, 1 = nothing to
 * read, 2 = a usage error; an unrecognised flag is refused, never ignored).
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// fileURLToPath, not resolve(import.meta.url): path.resolve on a `file://` URL
// does not strip the scheme on Windows — it produces `file:\D:\...`, ROOT becomes
// a relative junk path and `--dist dist` resolves to `<cwd>\file:\D:\...\dist`,
// so the script failed with "dist directory not found" before reading a byte.
// Every other script in this directory already uses fileURLToPath for this reason.
const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));

const argv = process.argv.slice(2);
let distArg = "dist";
let top = 20;
let jsonOut = null;
for (let i = 0; i < argv.length; i++) {
  const flag = argv[i];
  if (flag === "--dist") {
    distArg = argv[++i] ?? "";
    if (!distArg) {
      console.error("bundle-atlas.mjs: --dist needs a directory");
      process.exit(2);
    }
  } else if (flag === "--top") {
    top = Number(argv[++i]);
    if (!Number.isFinite(top) || top <= 0) {
      console.error(`bundle-atlas.mjs: --top wants a positive number, got '${argv[i]}'`);
      process.exit(2);
    }
  } else if (flag === "--json") {
    jsonOut = argv[++i] ?? "";
    if (!jsonOut) {
      console.error("bundle-atlas.mjs: --json needs a path");
      process.exit(2);
    }
  } else {
    console.error(`bundle-atlas.mjs: unrecognised argument '${flag}' (accepted: --dist, --top, --json)`);
    process.exit(2);
  }
}

const distDir = resolve(ROOT, distArg);
if (!existsSync(distDir)) {
  console.error(`FAIL  dist directory not found: ${distDir} (run \`pnpm build\` first)`);
  process.exit(1);
}

/** Every `.js.map` under the dist assets directory. */
function findMaps(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...findMaps(p));
    else if (entry.name.endsWith(".js.map")) out.push(p);
  }
  return out;
}

/**
 * Attribute generated bytes to sources.
 *
 * A VLQ-decoded segment's source index is what matters here. Two things the old version
 * of this function got wrong, verified against `@jridgewell/sourcemap-codec`'s `decode()`
 * (already in the pnpm store as a transitive dependency — used for the check, not
 * imported by this script):
 *
 *   1. The source index is `fields[1]`, and it is RELATIVE: it accumulates over the whole
 *      `mappings` string, while only the generated column (`fields[0]`) resets per line.
 *      Reading `fields[3]` (the original column delta) as an absolute index attributed
 *      bytes to whichever sources happen to sit at small indices.
 *   2. The per-chunk total is generated BYTES — the sum of each generated line's final
 *      column — not the longest mappings line's character count. Measured on
 *      `vendor-react-dom-*.js`: this method totals 206948 against a `stat` of 206957 B.
 *
 * Walking `mappings` directly (rather than depending on `source-map`) keeps this script
 * dependency-free, which is the rule every checker in `scripts/` follows.
 */
function attribute(mapText) {
  const map = JSON.parse(mapText);
  const sources = map.sources ?? [];
  if (!sources.length) return { rows: [], totalBytes: 0 };

  const counts = new Array(sources.length).fill(0);
  let sourceIndex = 0;
  let chunkBytes = 0;
  for (const line of (map.mappings ?? "").split(";")) {
    let genColumn = 0;
    for (const seg of line.split(",")) {
      if (!seg) continue;
      const fields = decodeVlq(seg);
      if (!fields.length) continue;
      genColumn += fields[0];
      if (fields.length >= 4) {
        sourceIndex += fields[1];
        if (sourceIndex >= 0 && sourceIndex < counts.length) counts[sourceIndex] += 1;
      }
    }
    chunkBytes += genColumn;
  }
  if (!chunkBytes) return { rows: [], totalBytes: 0 };

  const totalSegments = counts.reduce((a, b) => a + b, 0) || 1;
  const rows = [];
  for (let i = 0; i < sources.length; i++) {
    if (!counts[i]) continue;
    const share = counts[i] / totalSegments;
    rows.push({
      source: sources[i],
      package: packageNameOf(sources[i]),
      segments: counts[i],
      // The apportioned figure: what share of the generated chunk came from this source.
      approxBytes: Math.round(chunkBytes * share),
    });
  }
  return { rows, totalBytes: chunkBytes };
}

/** Minimal Base64-VLQ decoder — only the integer fields are needed here. */
function decodeVlq(text) {
  const chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  const values = [];
  let shift = 0;
  let value = 0;
  for (const ch of text) {
    const digit = chars.indexOf(ch);
    if (digit < 0) break;
    value += (digit & 31) << shift;
    if (digit & 32) {
      shift += 5;
    } else {
      const negative = value & 1;
      value >>= 1;
      values.push(negative ? -value : value);
      value = 0;
      shift = 0;
    }
  }
  return values;
}

/** `node_modules/zustand/esm/index.mjs` → `zustand`; `src/App.tsx` → `(app code)`. */
function packageNameOf(source) {
  const cleaned = source.replace(/\\/g, "/");
  const nm = cleaned.lastIndexOf("node_modules/");
  if (nm < 0) return "(app code)";
  const rest = cleaned.slice(nm + "node_modules/".length);
  const parts = rest.split("/");
  if (parts[0].startsWith("@") && parts.length > 1) return `${parts[0]}/${parts[1]}`;
  return parts[0];
}

const maps = findMaps(join(distDir, "assets"));
if (maps.length === 0) {
  console.error(`FAIL  no .js.map files under ${join(distDir, "assets")}`);
  process.exit(1);
}

const byPackage = new Map();
let appBytes = 0;
let totalBytes = 0;
for (const p of maps) {
  const { rows, totalBytes: chunkBytes } = attribute(readFileSync(p, "utf8"));
  totalBytes += chunkBytes;
  for (const row of rows) {
    const key = row.package;
    byPackage.set(key, (byPackage.get(key) ?? 0) + row.approxBytes);
    if (key === "(app code)") appBytes += row.approxBytes;
  }
}

const ranked = [...byPackage.entries()].sort((a, b) => b[1] - a[1]);
console.log(`DevHub bundle atlas — ${maps.length} sourcemaps under ${distArg}`);
console.log(`generated bytes attributed: ${totalBytes.toLocaleString()} (approximate, see the header)`);
console.log("");
console.log("PACKAGE                 APPROX_BYTES   SHARE");
for (const [name, bytes] of ranked.slice(0, top)) {
  console.log(
    `${name.padEnd(22)} ${bytes.toLocaleString().padStart(12)}   ${((bytes / (totalBytes || 1)) * 100)
      .toFixed(1)
      .padStart(5)}%`,
  );
}
console.log("");
console.log(`app code vs dependencies: ${appBytes.toLocaleString()} / ${(totalBytes - appBytes).toLocaleString()}`);

if (jsonOut) {
  const target = resolve(ROOT, jsonOut);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(
    target,
    JSON.stringify({ generatedAt: new Date().toISOString(), maps: maps.length, totalBytes, packages: ranked }, null, 2),
  );
  console.log(`wrote ${jsonOut}`);
}
