/**
 * Per-repository Docker isolation (r20-N3-1).
 *
 * REQUIREMENTS.md §3.6 lists five isolation dimensions; four are implemented in-app
 * (path, venv, port block, worktree). The fifth — 服务/数据库 via "Docker 每项目独立网络 +
 * 命名卷" — was recorded as *design verified* and never built, and the branch that was
 * opened for it (`feat/n1-docker-compose`) has zero commits. This module is the
 * naming half of that dimension.
 *
 * ## Why names are the whole problem
 *
 * Compose derives its network and volume names from the *project name*, which defaults
 * to the containing directory. Two repositories cloned under different directories
 * already get separate default networks, so the naive "isolation" is accidental and
 * breaks the moment someone runs `docker compose -f <other>/docker-compose.yml
 * --project-directory …`, or when two repositories ship a service that names a volume
 * `db-data` — a short name resolves to `<project>_db-data`, so the collision is only in
 * the *project* part. This module therefore owns one decision: a project name derived
 * from the repository's slug, so every network, volume and container label in `docker
 * ps` says which repository it belongs to.
 *
 * ## What is deliberately not here
 *
 * Nothing starts a container, and nothing rewrites a repository's own compose file. The
 * app's boundary (REQUIREMENTS §3.1: 项目容器与启动器, not a Docker UI) says the product
 * shows and prepares, and the person runs. `isolatedOverride` produces the file content
 * the 项目设置 panel can offer to save; `compose config` validation of that content is
 * what `scripts/check-compose.mjs` measures.
 */

/** Compose project names must match `[a-z0-9][a-z0-9_-]*` in practice; a slug is
 * `owner/repo` and can carry anything a filesystem allowed, so it is folded, not
 * trusted. */
export function composeProjectName(slug: string): string {
  const folded = slug
    .toLowerCase()
    .replace(/[^a-z0-9_-]+/g, "-")
    .replace(/^[-_]+/, "")
    .replace(/[-_]+$/, "");
  // Compose refuses a project name that is not a leading alphanumeric, and an empty
  // slug must still produce a usable name rather than `_default`. Leading punctuation is
  // stripped by the fold above; a slug that is *only* punctuation collapses to nothing,
  // so it gets a prefix rather than an empty string.
  const trimmed = folded.replace(/[-_]+$/, "");
  const safe = /^[a-z0-9]/.test(trimmed) ? trimmed : `repo-${trimmed.replace(/^[-_]+/, "")}`;
  return safe.slice(0, 40).replace(/[-_]$/, "") || "repo";
}

/** The network every service of one repository is attached to. */
export function composeNetworkName(slug: string): string {
  return `${composeProjectName(slug)}_devhub`;
}

/** A named volume, qualified by the project, exactly the way compose itself would
 * resolve `<project>_<name>` — stated explicitly so a `docker volume ls` line can be
 * read back to a repository without guessing. */
export function composeVolumeName(slug: string, volume: string): string {
  const name = volume.toLowerCase().replace(/[^a-z0-9_-]+/g, "-").replace(/^[-_]+/, "");
  return `${composeProjectName(slug)}_${name || "data"}`;
}

/**
 * The override file content that pins one repository's compose project to its own
 * network and to project-qualified volume names.
 *
 * Written as a *separate* file (`devhub-isolation.yml`) rather than an edit of the
 * repository's own `docker-compose.yml`: the app must not rewrite someone's source tree
 * (REQUIREMENTS §5.2, 不污染用户环境), and compose's documented `-f a -f b` merge order
 * gives the override the last word without touching the first file.
 *
 * `volumes` are the *short* names the project's own file uses; each is re-declared with
 * `name:` so the on-disk volume is project-qualified even if the repository's file did
 * not qualify it.
 */
export function isolatedOverride(
  slug: string,
  services: readonly string[],
  volumes: readonly string[],
): string {
  const network = composeNetworkName(slug);
  const lines: string[] = [
    "# Generated by DevHub (r20-N3). Do not edit by hand; the panel rewrites it.",
    "# Attach every service of this repository to one project-private network.",
    "networks:",
    `  ${network}:`,
    "    external: false",
    "",
  ];
  if (services.length > 0) {
    lines.push("services:");
    for (const svc of services) {
      lines.push(`  ${svc}:`, "    networks:", `      - ${network}`);
    }
    lines.push("");
  }
  if (volumes.length > 0) {
    lines.push("volumes:");
    for (const vol of volumes) {
      lines.push(`  ${vol}:`, `    name: ${composeVolumeName(slug, vol)}`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

/** The two-file command a person (or the 启动面板) runs to get the isolated view. */
export function isolatedComposeCommand(
  slug: string,
  baseFile = "docker-compose.yml",
  overrideFile = "devhub-isolation.yml",
): string {
  return [
    "docker compose",
    `-p ${composeProjectName(slug)}`,
    `-f ${baseFile}`,
    `-f ${overrideFile}`,
  ].join(" ");
}

/**
 * The top-level `services:` / `volumes:` keys a repository's own compose file
 * declares (r21-N2-2), read straight from the text the panel already loaded.
 *
 * ## Why a scanner and not a YAML parser
 *
 * This repository has no YAML dependency and is not going to grow one for one
 * panel (zero-runtime-dependency is a REQUIREMENTS §5.1 constraint, and every
 * dependency here would be a supply-chain row in `pnpm sbom`). So this reads the
 * one shape compose files actually use — a block mapping under an unindented
 * `services:` / `volumes:` key — and refuses everything else instead of guessing.
 *
 * ## The three answers, and why `null` is not `[]`
 *
 *   `["web", …]`  the block is there and every entry line was recognised;
 *   `[]`          no such top-level key in this file (nothing to declare);
 *   `null`        the key is there but the entries could not be read reliably —
 *                 flow style (`services: {}`), tab indentation, an anchor on a
 *                 key, an entry with an inline value, a stray line at the entry
 *                 indentation. Producing `[]` here would turn "I could not read
 *                 it" into "there is none", and the panel would render an
 *                 override that quietly omits a service or a volume pin.
 *
 * The conservative rule that makes `null` rare in practice: inside the block,
 * only lines indented by exactly two spaces may be entries (deeper lines belong
 * to the previous entry's body and are skipped), and **any** two-space line that
 * is not `key:` aborts the block. A file whose structure surprises this scanner
 * gets an honest "没认出" in the panel, never a half-list.
 */
export type ComposeDeclarations = {
  services: string[] | null;
  volumes: string[] | null;
};

/** Read one top-level block mapping. See [`composeDeclarations`]. */
function readTopLevelBlock(lines: string[], key: string): string[] | null {
  let start = -1;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i] ?? "";
    if (line.startsWith("#")) continue;
    if (!line.startsWith(`${key}:`)) continue;
    const rest = line.slice(key.length + 1);
    // `services: …` with something other than a comment after the colon is flow
    // style or a scalar — a shape this scanner does not read.
    if (rest.replace(/#.*$/, "").trim() !== "") return null;
    start = i;
    break;
  }
  if (start < 0) return [];

  const names: string[] = [];
  for (let i = start + 1; i < lines.length; i++) {
    const line = lines[i] ?? "";
    if (line.trim() === "" || /^\s*#/.test(line)) continue;
    if (line.startsWith("\t")) return null;
    const indent = /^ */.exec(line)?.[0].length ?? 0;
    if (indent === 0) break; // the next top-level key ends this block
    const name = /^ {2}(['"]?)([A-Za-z0-9][A-Za-z0-9_.-]*)\1:\s*(#.*)?$/.exec(line)?.[2];
    if (indent === 2) {
      if (name === undefined) return null; // indented by two but not a `key:` — unreadable
      names.push(name);
      continue;
    }
    // Deeper lines are the previous entry's body — unless there is no previous
    // entry, which is not the shape this scanner claims to read. Indent 1 is
    // neither (a stray space before a would-be entry) and must not be skipped.
    if (indent < 3 || names.length === 0) return null;
  }
  return names.length > 0 ? names : null;
}

/** The declarations of one compose file's text (see the type for the three answers). */
export function composeDeclarations(text: string): ComposeDeclarations {
  const lines = text.split(/\r?\n/);
  return {
    services: readTopLevelBlock(lines, "services"),
    volumes: readTopLevelBlock(lines, "volumes"),
  };
}
