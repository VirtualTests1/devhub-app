/**
 * 界面英文化（i18n）的词条基础设施 —— r16-n2 的第一项。
 *
 * Honest scope, stated once so no later reader over-reads it: this is a
 * **partial** wiring. Only the surfaces a later sub-direction actually connects
 * (nav labels, 设置 catalog titles, the palette's 去… actions, the title-bar
 * tooltips, the language row itself) resolve through this dictionary; every
 * other string in the app keeps its existing Chinese literal. REQUIREMENTS.md
 * still lists 界面英文化 under 明确未做, and that stays true until the wiring
 * is honestly complete — this module is the start, not the claim.
 *
 * ## Missing-key policy (the contract the tests pin)
 *
 *   1. A key present in the requested locale renders that entry.
 *   2. A key missing from the requested locale falls back to the **zh-CN**
 *      entry — the default-language fallback. An `en` gap therefore shows
 *      today's Chinese text, never a blank and never a raw key.
 *   3. A key missing from zh-CN too (an unknown key — a programming error)
 *      renders **the key itself** and logs a one-per-key `console.warn`. The
 *      key-as-text is the debuggable degradation; the warn is the dev-time
 *      visibility. A test that enumerates every wired key (tests/i18n.test.ts)
 *      is what keeps case 3 from ever reaching the UI.
 *   4. An empty-string entry is treated as missing (cases 2–3), so a half-filled
 *      dictionary can never render an empty label.
 *
 * ## Persistence: localStorage, deliberately NOT the Rust config
 *
 * The language preference round-trips through `localStorage`
 * (`devhub.i18n.locale.v1`), the same local-pref pattern `store/ui.ts` uses for
 * navigation (`NAV_KEY`, readNav/persistNav). The alternative — a settings field
 * on the backend — does not exist to be used without editing Rust:
 * `AppConfig` (src-tauri/src/lib.rs:3998-4077) and `SettingsUpdate`
 * (src-tauri/src/lib.rs:4561-4594) are closed structs with typed fields and no
 * `#[serde(flatten)]` open map; an extra JSON field is silently dropped by
 * serde, not stored. This direction forbids touching Rust, so a frontend-held
 * preference is not a compromise, it is the only honest route — and a UI
 * language is genuinely webview-side state anyway.
 *
 * ## Why no React import lives here
 *
 * The task contract for this file: Node-importable, no React-only imports at
 * module top, so `tests/` can cover the dictionary and the store directly (the
 * repo's runner is `node --experimental-strip-types --test`, and
 * `tests/lib-import-graph.test.ts` loads every `src/lib/**` module). The React
 * hook therefore lives in the sibling `useI18n.ts`; this module stays a pure
 * store + lookup with zero runtime dependencies.
 */

