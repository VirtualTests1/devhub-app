/**
 * Membership test against the zh table (the canonical key set).
 *
 * Stored ids are untrusted — a 常用 page can carry `view:` entries from an
 * imported list that name a deleted route — so callers that build a key from a
 * runtime string route through here and degrade to the raw id, which is what
 * the catalog lookups they replace did (`?? entry.id`).
 */
export function isTranslationKey(key: string): key is TranslationKey {
  return Object.prototype.hasOwnProperty.call(ZH, key);
}

/** `view.${id}` when the dictionary knows the view, else the raw id. */
export function viewTitle(t: TFunc, id: string): string {
  const key = `view.${id}`;
  return isTranslationKey(key) ? t(key) : id;
}

/** `settings.section.${id}` when the dictionary knows the section, else the raw id. */
export function sectionTitle(t: TFunc, id: string): string {
  const key = `settings.section.${id}`;
  return isTranslationKey(key) ? t(key) : id;
}
